import { test } from "../e2e/support/test.js";
import { signIn } from "../e2e/support/auth.js";
import { ASSESSOR_EMAIL } from "../fixtures/data.js";
import { snap, openSection, closeDrawer } from "./lib.js";

const topbar = (page) => page.locator("header.topbar, .topbar").first();

test("facilitator portal", async ({ page }) => {
  await signIn(page, { role: "facilitator" });
  const card = page.locator("main section.card").filter({ has: page.locator(".host-key") }).first();
  await card.waitFor();
  await snap(page, "signin-5-header", { clip: topbar(page), hl: page.getByRole("button", { name: /Sign out/ }), pad: 8 });
  await snap(page, "tour-fac-3-header", { clip: topbar(page), hl: page.locator("button.help-btn"), pad: 8 });
  await snap(page, "tour-fac-1-portal", { clip: page.locator("main"), pad: 0, top: true });
  await snap(page, "portal-1-portal", { clip: page.locator("main"), hl: page.getByRole("heading", { name: "Your circles" }), pad: 0, top: true });
  await snap(page, "tour-fac-2-card", { clip: card, hl: card.locator(".host-key"), pad: 12 });
  const details = card.locator(".details").first();
  await snap(page, "portal-2-details", { clip: details, hl: details.locator(".detail").first(), pad: 14 });
  await snap(page, "portal-3-hostkey", { clip: card.locator(".host-key"), hl: card.locator(".host-key").getByRole("button", { name: "Show" }), pad: 18 });
  await snap(page, "portal-4-copy", { clip: card.locator(".copy-all"), hl: card.locator(".copy-all"), pad: 18 });
  await snap(page, "portal-5-steps", { clip: card.locator("ol.steps"), hl: card.locator("ol.steps"), pad: 18 });
  await snap(page, "portal-6-links", { clip: card.locator(".details").last(), hl: card.locator(".details").last(), pad: 14 });
  await snap(page, "facreq-1-link", { clip: card.locator(".request").first(), hl: card.getByRole("button", { name: "Need to change something?" }), pad: 24 });
  await card.getByRole("button", { name: "Need to change something?" }).click();
  const form = card.locator("form.request-form");
  await form.waitFor();
  await snap(page, "facreq-2-type", { clip: form, hl: form.locator("select").first(), pad: 14 });
  await form.locator("select").first().selectOption("change_time");
  await form.locator("select").nth(1).selectOption("3");
  await form.locator("input[type=time]").fill("19:30");
  await form.locator("input[type=date]").first().fill("2026-11-04");
  await form.locator("textarea").fill("Our group prefers Wednesday evenings now.");
  await snap(page, "facreq-3-details", { clip: form, hl: form.getByRole("button", { name: "Send request" }), pad: 14 });
  await page.getByRole("button", { name: "Send request" }).click();
  await page.waitForTimeout(600);
  const hist = card.locator(".history").first();
  await hist.waitFor();
  await snap(page, "facreq-4-history", { clip: hist, hl: hist, pad: 18 });
  await page.evaluate(() => window.scrollTo(0, 0));
  const prof = page.locator("section.profile-card");
  await snap(page, "facdet-1-button", { clip: prof, hl: prof.getByRole("button", { name: "Edit my details" }), pad: 16 });
  await snap(page, "tour-fac-4-edit", { clip: prof, hl: prof.getByRole("button", { name: "Edit my details" }), pad: 16 });
  await prof.getByRole("button", { name: "Edit my details" }).click();
  await page.waitForTimeout(300);
  await snap(page, "facdet-2-form", { clip: prof, hl: prof.getByLabel("Phone (with country code)"), pad: 16 });
});

test("assessor view", async ({ page }) => {
  await signIn(page, { role: "assessor", email: ASSESSOR_EMAIL });
  const list = page.locator("section.tr-page");
  await list.waitFor();
  await page.waitForTimeout(500);
  await snap(page, "tour-ass-1-list", { clip: page.locator("main"), hl: page.getByRole("heading", { name: /^Trainees assigned/ }), pad: 0, top: true });
  await snap(page, "ass-1-list", { clip: list, hl: page.locator(".tr-row", { hasText: "Hari" }).first(), pad: 12 });
  await snap(page, "tour-ass-2-filters", { clip: list.locator(".web-filter"), hl: list.locator(".web-filter"), pad: 16 });
  await snap(page, "tour-ass-3-row", { clip: page.locator(".tr-row", { hasText: "Hari" }).first(), hl: page.locator(".tr-row", { hasText: "Hari" }).first(), pad: 14 });
  await page.locator(".tr-row", { hasText: "Hari" }).first().click();
  const drawer = page.locator(".tr-drawer");
  await drawer.waitFor();
  await page.waitForTimeout(400);
  await snap(page, "ass-2-panel", { clip: drawer, hl: drawer.locator("section[aria-label=Training]"), pad: 0 });
  const train = drawer.locator("section[aria-label=Training]");
  await snap(page, "ass-3-answers", { clip: train, hl: train.getByText("Answers").first(), pad: 14 });
  await snap(page, "ass-4-video", { clip: train, hl: train.getByText(/Video assessment/).first(), pad: 14 });
  const assess = drawer.locator("section[aria-label=Assessment]");
  await openSection(page, "Assessment");
  await snap(page, "score-1-section", { clip: assess.locator(".sec-head"), hl: assess.locator(".sec-toggle"), pad: 20 });
  await snap(page, "score-2-criteria", { clip: assess, hl: assess.locator(".tr-criterion").first(), pad: 16 });
  const fb = assess.locator("textarea").last();
  await fb.fill("Warm and clear. Keep slowing down at the key verses.");
  await snap(page, "score-3-feedback", { clip: [fb, assess.getByRole("button", { name: /Save assessment|Saved/ })], hl: fb, pad: 16 });
});
